// Concatenate every migration (in order) into dist/schema.sql, for pasting into the Supabase SQL editor when the CLI is not available.
// Usage: node packages/db/scripts/bundle.mjs [--seed]     (--seed appends the FAKE demo tenants; dev projects only)
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
let out = `-- Generated by packages/db/scripts/bundle.mjs — ${files.length} migrations in order. Do not edit; edit the migrations.\n`;
for (const f of files) out += `\n-- ======================================================================== ${f}\n${readFileSync(join(dir, f), 'utf8')}\n`;
if (process.argv.includes('--seed')) out += `\n-- ======================================================================== seed.sql (FAKE demo data)\n${readFileSync(join(root, 'supabase', 'seed.sql'), 'utf8')}\n`;
mkdirSync(join(root, 'dist'), { recursive: true });
const target = join(root, 'dist', 'schema.sql');
writeFileSync(target, out);
console.log(`${files.length} migrations -> ${target} (${(out.length / 1024).toFixed(0)} KB)`);
